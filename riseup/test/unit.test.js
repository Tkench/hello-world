test('buildCss emits only settings that are set, and sanitises values', () => {
  const c = config.defaultCourseConfig();
  assert.equal(css.buildCss(c).trim(), '/* Generated by RiseUp */');
  c.globalStyles.blockRadius = 12;
  c.globalStyles.blockShadow = 'soft';
  c.globalStyles.linkColor = 'red; } body { display:none';
  c.globalStyles.buttonTextTransform = 'uppercase';
  const out = css.buildCss(c);
  assert.match(out, /border-radius: 12px !important/);
  assert.match(out, /box-shadow: 0 1px 3px/);
  assert.match(out, /text-transform: uppercase !important/);
  assert.doesNotMatch(out, /display:none/);
});

test('text styles become classes, gradients use background-clip', () => {
  const out = css.textStyleCss({ id: 's-1', fontFamily: 'Lora', fontWeight: '700', gradientFrom: '#ff0000', gradientTo: '#0000ff', gradientAngle: 45 });
  assert.match(out, /^\.ru-style-s-1 \{/);
  assert.match(out, /font-family: 'Lora', inherit/);
  assert.match(out, /linear-gradient\(45deg, #ff0000, #0000ff\)/);
  assert.match(out, /background-clip: text/);
  assert.equal(css.textStyleCss({ id: 's-2', fontFamily: "Evil'); x" }).includes('Evil'), false);
});

