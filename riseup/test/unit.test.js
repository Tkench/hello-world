test('patchCourseZip injects once and replaces earlier runs', async () => {
  const zip = new JSZip();
  zip.file('index.html', '<html><head></head><body>launcher</body></html>');
  zip.file('scormcontent/index.html', '<html><head><title>C</title></head><body><div id="app"></div></body></html>');
  const cfg = config.defaultCourseConfig();
  cfg.globalStyles.blockRadius = 10;
  cfg.fonts = [{ family: 'Lora', weights: [400] }];
  cfg.textStyles = [{ id: 's1', fontFamily: 'Lora' }];
  cfg.textRules = [{ id: 'r1', text: 'Hi</script>', styleId: 's1' }];
  const assets = { runtimeJs: '/*rt*/', textRulesJs: '/*tr*/' };
  const res = await pkg.patchCourseZip(zip, cfg, assets);
  assert.equal(res.index, 'scormcontent/index.html');
  await pkg.patchCourseZip(zip, cfg, { ...assets, fontCss: '@font-face{}', fontFiles: [{ name: 'lora.woff2', data: new Uint8Array([1]) }] });
  const html = await zip.file('scormcontent/index.html').async('string');
  assert.equal(html.split('riseup/riseup.css').length - 1, 1);
  assert.match(html, /href="riseup\/fonts\.css"/);
  assert.doesNotMatch(html, /fonts\.googleapis/);
  assert.equal(await zip.file('index.html').async('string'), '<html><head></head><body>launcher</body></html>');
  assert.match(await zip.file('scormcontent/riseup/riseup.css').async('string'), /border-radius: 10px/);
  const cfgJs = await zip.file('scormcontent/riseup/riseup-config.js').async('string');
  assert.doesNotMatch(cfgJs, /<\/script>/);
  assert.ok(zip.file('scormcontent/riseup/fonts/lora.woff2'));
});

