test('wrapTextRules wraps phrases, is idempotent and reversible', () => {
  const dom = new JSDOM('<div id="r"><p>Safety first. Safety <b>always</b>.</p><p contenteditable="true">Safety here</p><script>Safety</script></div>');
  const root = dom.window.document.getElementById('r');
  const styles = [{ id: 's1' }];
  const r = [{ id: 'r1', text: 'Safety', styleId: 's1', matchCase: true }];
  assert.equal(rules.wrapTextRules(root, r, styles, { skipEditable: true }), 2);
  assert.equal(rules.wrapTextRules(root, r, styles, { skipEditable: true }), 0);
  assert.equal(root.querySelectorAll('span.ru-style-s1').length, 2);
  assert.equal(root.querySelector('p').textContent, 'Safety first. Safety always.');
  rules.unwrapTextRules(root);
  assert.equal(root.querySelectorAll('span').length, 0);
  assert.equal(root.querySelector('p').textContent, 'Safety first. Safety always.');
});

