const XLF = `<?xml version="1.0" encoding="UTF-8"?>
<xliff version="1.2" xmlns="urn:oasis:names:tc:xliff:document:1.2">
  <file original="course" source-language="en" datatype="html">
    <body>
      <trans-unit id="t1"><source>&lt;p&gt;Welcome to Acme. &lt;strong&gt;Acme&lt;/strong&gt; cares.&lt;/p&gt;</source></trans-unit>
      <trans-unit id="t2"><source>Contact <g id="1">Acme</g> support</source><target>Contact <g id="1">Acme</g> support</target></trans-unit>
      <trans-unit id="t3"><source>Nothing here about strong things</source></trans-unit>
    </body>
  </file>
</xliff>`;
const env = (() => { const w = new JSDOM('').window; return { DOMParser: w.DOMParser, XMLSerializer: w.XMLSerializer }; })();

test('XLIFF preview counts visible text only', () => {
  const hits = xliff.previewXliff(XLF, 'Acme', { matchCase: true }, env);
  assert.deepEqual(hits.map((h) => [h.unitId, h.count]), [['t1', 2], ['t2', 1]]);
  // "strong" appears in escaped tags of t1 but only in the text of t3
  assert.deepEqual(xliff.previewXliff(XLF, 'strong', {}, env).map((h) => h.unitId), ['t3']);
});

test('XLIFF replace edits targets, adds missing targets, leaves markup alone', () => {
  const r = xliff.replaceInXliff(XLF, 'Acme', 'Globex', { matchCase: true }, env);
  assert.equal(r.count, 3);
  assert.equal(r.changedUnits, 2);
  const doc = new env.DOMParser().parseFromString(r.xml, 'application/xml');
  const targets = Array.from(doc.getElementsByTagName('target')).map((t) => t.textContent);
  assert.equal(targets.length, 3);
  assert.equal(targets[0], '<p>Welcome to Globex. <strong>Globex</strong> cares.</p>');
  assert.equal(targets[1], 'Contact Globex support');
  assert.equal(targets[2], 'Nothing here about strong things');
  assert.match(doc.getElementsByTagName('source')[0].textContent, /Acme/); // sources untouched
  assert.equal(doc.getElementsByTagName('g').length, 2); // inline tags kept
  assert.match(r.xml, /^<\?xml/);
  assert.throws(() => xliff.replaceInXliff('<html/>', 'a', 'b', {}, env), /No translation units/);
});

