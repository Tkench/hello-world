test('findMatches handles case and whole words', () => {
  assert.deepEqual(rules.findMatches('Cat cat concat', 'cat', {}), [0, 4, 11]);
  assert.deepEqual(rules.findMatches('Cat cat concat', 'cat', { matchCase: true }), [4, 11]);
  assert.deepEqual(rules.findMatches('Cat cat concat', 'cat', { wholeWord: true }), [0, 4]);
  assert.deepEqual(rules.findMatches('aaaa', 'aa', {}), [0, 2]);
  assert.deepEqual(rules.findMatches('café cafés', 'café', { wholeWord: true }), [0]);
});

test('wrapTextRules wraps phrases, is idempotent and reversible', () => {
  const dom = new JSDOM('<div id="r"><p>Safety first. Safety <b>always</b>.</p><p contenteditable="true">Safety here</p><script>Safety</script></div>');
  const root = dom.window.document.getElementById('r');
  const styles = [{ id: 's1' }];
  const r = [{ id: 'r1', text: 'Safety', styleId: 's1', matchCase: true }];
  assert.equal(rules.wrapTextRules(root, r, styles, { skipEditable: true }), 2);
  assert.equal(rules.wrapTextRules(root, r, styles, { skipEditable: true }), 0);
  assert.equal(root.querySelectorAll('span.ru-style-s1').length, 2);
  assert.equal(root.querySelector('p').textContent, 'Safety first. Safety always.');
  rules.unwrapTextRules(root);
  assert.equal(root.querySelectorAll('span').length, 0);
  assert.equal(root.querySelector('p').textContent, 'Safety first. Safety always.');
});

test('longer phrases win over phrases they contain', () => {
  const dom = new JSDOM('<div id="r">fire safety plan</div>');
  const root = dom.window.document.getElementById('r');
  const styles = [{ id: 'a' }, { id: 'b' }];
  rules.wrapTextRules(root, [
    { id: '1', text: 'safety', styleId: 'a' },
    { id: '2', text: 'fire safety', styleId: 'b' },
  ], styles, {});
  assert.equal(root.innerHTML, '<span class="ru-style-b" data-riseup-rule="2">fire safety</span> plan');
});

